@app.route("/api/reports", methods=["GET"])
def api_list_reports():
    hashes = read_json(HASH_FILE)

    reports = {}
    for entry in hashes:
        filename = entry["filename"]
        report_id = filename.rsplit(".", 1)[0]
        ext = filename.rsplit(".", 1)[1]

        if report_id not in reports:
            reports[report_id] = {"report_id": report_id, "created_at": entry["created_at"]}

        reports[report_id][f"{ext}_filename"] = filename
        reports[report_id][f"{ext}_hash"] = entry["sha256"]

    return jsonify(list(reports.values())[::-1])


