@app.route("/verify", methods=["GET", "POST"])
def verify_report():
    if request.method == "GET":
        return render_template("index.html")

    file = request.files.get("report")
    valid, message = validate_uploaded_file(file)

    if not valid:
        return render_template(
            "index.html",
            verification_message=message,
            verification_status="error"
        ), 400

    filename = secure_filename(file.filename)
    upload_path = os.path.join(UPLOAD_FOLDER, filename)
    file.save(upload_path)
    uploaded_hash = calculate_sha256(upload_path)
    original_hash = find_original_hash(filename)

    if original_hash is None:
        add_audit_log("REPORT_VERIFICATION", filename, "UNKNOWN_REPORT")
        message = "Report not found in the system registry."
        status = "error"
    elif uploaded_hash == original_hash:
        add_audit_log("REPORT_VERIFICATION", filename, "VERIFIED")
        message = "Report Verified - Integrity Confirmed."
        status = "success"
    else:
        add_audit_log("REPORT_VERIFICATION", filename, "MODIFIED")
        message = "Verification Failed - Report integrity mismatch detected."
        status = "error"

    return render_template(
        "index.html",
        verification_message=message,
        verification_status=status,
        uploaded_hash=uploaded_hash
    )


