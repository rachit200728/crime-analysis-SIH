ALLOWED_EXTENSIONS = {"pdf", "txt"}


def calculate_sha256(file_path):
    sha256 = hashlib.sha256()

    with open(file_path, "rb") as file:
        while True:
            chunk = file.read(4096)

            if not chunk:
                break

            sha256.update(chunk)

    return sha256.hexdigest()


def read_json(file_path):
    if not os.path.exists(file_path):
        return []

    try:
        with open(file_path, "r", encoding="utf-8") as file:
            data = json.load(file)
            return data if isinstance(data, list) else []
    except (OSError, json.JSONDecodeError):
        return []


def write_json(file_path, data):
    with open(file_path, "w", encoding="utf-8") as file:
        json.dump(data, file, indent=4)


def add_audit_log(action, filename, status):
    logs = read_json(AUDIT_FILE)

    logs.append({
        "timestamp": datetime.now().isoformat(),
        "action": action,
        "filename": filename,
        "status": status
    })

    write_json(AUDIT_FILE, logs)


def create_text_report(report_id, case_id, title, analyst, summary, findings):
    filename = f"{report_id}.txt"
    path = os.path.join(REPORT_FOLDER, filename)

    report = f"""AI-POWERED CRIMINAL NETWORK ANALYSIS SYSTEM
CASE ANALYSIS REPORT

Report ID: {report_id}
Case ID: {case_id}
Case Title: {title}
Generated By: {analyst}
Generated At: {datetime.now().strftime("%d-%m-%Y %H:%M:%S")}

--------------------------------------------------

CASE SUMMARY

{summary}

--------------------------------------------------

ANALYSIS FINDINGS

{findings}

--------------------------------------------------

SYSTEM NOTICE

This report was generated by the Criminal Network Analysis System.
Report integrity can be verified using the associated SHA-256 seal.
"""

    with open(path, "w", encoding="utf-8") as file:
        file.write(report)

    return filename, path


def create_pdf_report(report_id, case_id, title, analyst, summary, findings):
    filename = f"{report_id}.pdf"
    path = os.path.join(REPORT_FOLDER, filename)

    pdf = canvas.Canvas(path, pagesize=A4)
    width, height = A4
    y = height - 60

    pdf.setFont("Helvetica-Bold", 16)
    pdf.drawString(50, y, "AI Criminal Network Analysis")
    y -= 25

    pdf.setFont("Helvetica-Bold", 13)
    pdf.drawString(50, y, "CASE ANALYSIS REPORT")
    y -= 40

    pdf.setFont("Helvetica", 10)
    information = [
        f"Report ID: {report_id}",
        f"Case ID: {case_id}",
        f"Case Title: {title}",
        f"Analyst: {analyst}",
        f"Generated: {datetime.now().strftime('%d-%m-%Y %H:%M:%S')}",
        "",
        "CASE SUMMARY",
        summary,
        "",
        "ANALYSIS FINDINGS",
        findings
    ]

    for item in information:
        wrapped_lines = textwrap.wrap(item, width=85) or [""]

        for line in wrapped_lines:
            if y < 60:
                pdf.showPage()
                y = height - 60
                pdf.setFont("Helvetica", 10)

            pdf.drawString(50, y, line)
            y -= 16

    pdf.save()
    return filename, path


def save_report_hash(filename, file_hash):
    hashes = read_json(HASH_FILE)

    hashes.append({
        "filename": filename,
        "sha256": file_hash,
        "created_at": datetime.now().isoformat()
    })

    write_json(HASH_FILE, hashes)


def find_original_hash(filename):
    hashes = read_json(HASH_FILE)

    for report in reversed(hashes):
        if report.get("filename") == filename:
            return report.get("sha256")

    return None


def allowed_file(filename):
    return (
        "." in filename
        and filename.rsplit(".", 1)[1].lower() in ALLOWED_EXTENSIONS
    )


def validate_uploaded_file(file):
    if not file or not file.filename:
        return False, "Please select a report before verification."

    if not allowed_file(file.filename):
        return False, "Unsupported file format. Upload a PDF or TXT report."

    extension = file.filename.rsplit(".", 1)[1].lower()
    first_bytes = file.stream.read(5)
    file.stream.seek(0)

    if extension == "pdf" and not first_bytes.startswith(b"%PDF-"):
        return False, "Invalid PDF file."

    return True, "File accepted."


