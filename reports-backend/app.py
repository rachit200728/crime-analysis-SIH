@app.route("/generate", methods=["GET", "POST"])
def generate_report():
    if request.method == "GET":
        return render_template("index.html")

    case_id = request.form.get("case_id", "").strip()
    title = request.form.get("title", "").strip()
    analyst = request.form.get("analyst", "").strip()
    summary = request.form.get("summary", "").strip()
    findings = request.form.get("findings", "").strip()

    if not all([case_id, title, analyst, summary, findings]):
        return render_template(
            "index.html",
            generation_message="Please complete every case report field.",
            generation_status="error"
        ), 400

    report_id = "REPORT-" + uuid.uuid4().hex[:8].upper()

    txt_filename, txt_path = create_text_report(
        report_id, case_id, title, analyst, summary, findings
    )
    pdf_filename, pdf_path = create_pdf_report(
        report_id, case_id, title, analyst, summary, findings
    )

    txt_hash = calculate_sha256(txt_path)
    pdf_hash = calculate_sha256(pdf_path)
    save_report_hash(txt_filename, txt_hash)
    save_report_hash(pdf_filename, pdf_hash)
    add_audit_log("REPORT_GENERATED", pdf_filename, "SUCCESS")

    return render_template(
        "index.html",
        generated=True,
        report_id=report_id,
        pdf_filename=pdf_filename,
        txt_filename=txt_filename,
        pdf_hash=pdf_hash,
        txt_hash=txt_hash
    )


